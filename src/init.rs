//! Interactive `morinet init` support: prompt loop + config generation.
//!
//! The prompt loop reads from an injected [`std::io::BufRead`] so it is fully
//! unit-testable without a TTY. The admin password is never read here — the
//! caller (main.rs) collects it masked via `rpassword` and passes it in.

use std::io::{BufRead, Write};

/// Answers collected by the interactive `morinet init` flow.
#[derive(Debug, Clone)]
pub struct InitAnswers {
    pub port: u16,
    pub data_dir: String,
    pub admin_email: String,
    /// Collected by the caller via `rpassword` (masked); empty until filled in.
    pub admin_password: String,
}

pub const DEFAULT_PORT: u16 = 8080;
pub const DEFAULT_DATA_DIR: &str = "./data";
pub const DEFAULT_ADMIN_EMAIL: &str = "admin@example.com";

/// Random cookie secret: 64 lowercase hex chars (32 bytes), built from two
/// UUIDv4 `simple()` hex strings — no extra RNG dependency.
pub fn generate_cookie_secret() -> String {
    let a = uuid::Uuid::new_v4().simple().to_string();
    let b = uuid::Uuid::new_v4().simple().to_string();
    format!("{a}{b}")
}

/// Render a Rust string as a quoted, escaped TOML string value.
fn toml_str(s: &str) -> String {
    toml::Value::String(s.to_string()).to_string()
}

/// Generate a commented `config.toml` from the interactive answers, modeled on
/// [`crate::default_config()`] — same section order and comments, with the
/// answers substituted and a real `[admin]` section carrying the bootstrap
/// credentials.
pub fn generate_config(
    port: u16,
    data_dir: &str,
    admin_email: &str,
    admin_password: &str,
    cookie_secret: &str,
) -> String {
    format!(
        r#"# morinet — generated config (created by `morinet init`)
# Edit values as needed; see comments per section.

[server]
bind_addr = {bind_addr}
# Must match the public origin behind TLS (e.g. https://morinet.treklair.fr),
# otherwise redirects and the session cookie are built on the wrong origin.
base_url = {base_url}

[storage]
data_dir = {data_dir}

[smtp]
host = "smtp.example.com"
port = 587
user = ""
pass = ""
from = "morinet@example.com"
starttls = true

[session]
# Auto-generated by `morinet init` (equivalent to: openssl rand -hex 32)
cookie_secret = {cookie_secret}
cookie_name = "morinet_session"

[admin]
# Bootstrap admin: applied at boot ONLY while the users table has no account
# with this email — set it once, then remove these lines if you like.
# This file holds the password in plaintext: chmod 600 advised.
# Env vars MORINET_ADMIN_EMAIL / MORINET_ADMIN_PASSWORD override these values.
email = {email}
password = {password}

[vaults]
# [[vaults.entries]]
# slug = "demo"
# name = "Demo vault"
# kind = "local"
# path = "./data/vaults/demo/src"
"#,
        bind_addr = toml_str(&format!("127.0.0.1:{port}")),
        base_url = toml_str(&format!("http://localhost:{port}")),
        data_dir = toml_str(data_dir),
        cookie_secret = toml_str(cookie_secret),
        email = toml_str(admin_email),
        password = toml_str(admin_password),
    )
}

/// Ask one question; empty input (or EOF) accepts the default shown in brackets.
fn ask(
    reader: &mut impl BufRead,
    writer: &mut impl Write,
    label: &str,
    default: &str,
) -> anyhow::Result<String> {
    write!(writer, "{label} [{default}]: ")?;
    writer.flush()?;
    let mut line = String::new();
    if reader.read_line(&mut line)? == 0 {
        return Ok(default.to_string());
    }
    let value = line.trim().to_string();
    Ok(if value.is_empty() {
        default.to_string()
    } else {
        value
    })
}

/// cargo-new-style prompt loop for port, data dir and admin email. The admin
/// password is NOT asked here — the caller reads it masked via `rpassword`
/// and fills in [`InitAnswers::admin_password`].
pub fn prompt_answers(
    reader: &mut impl BufRead,
    writer: &mut impl Write,
) -> anyhow::Result<InitAnswers> {
    let port = loop {
        let raw = ask(reader, writer, "Port", &DEFAULT_PORT.to_string())?;
        match raw.parse::<u16>() {
            Ok(p) if p > 0 => break p,
            _ => writeln!(
                writer,
                "Invalid port '{raw}'; enter a number between 1 and 65535."
            )?,
        }
    };
    let data_dir = ask(reader, writer, "Data dir", DEFAULT_DATA_DIR)?;
    let admin_email = ask(reader, writer, "Admin email", DEFAULT_ADMIN_EMAIL)?;
    Ok(InitAnswers {
        port,
        data_dir,
        admin_email,
        admin_password: String::new(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::BufReader;

    fn secret64() -> String {
        "aa".repeat(32)
    }

    #[test]
    fn generate_config_parses_and_carries_answers() {
        let out = generate_config(9090, "./vaultdata", "a@b.fr", "test-pass-9f3a", &secret64());
        let parsed: toml::Table = out.parse().expect("generated config must be valid TOML");
        assert!(out.contains("[server]"), "missing [server]");
        assert!(out.contains("[storage]"), "missing [storage]");
        assert!(out.contains("[session]"), "missing [session]");
        assert!(out.contains("[admin]"), "missing [admin]");
        assert!(out.contains("127.0.0.1:9090"), "port not in bind_addr");
        assert!(
            out.contains("http://localhost:9090"),
            "port not in base_url"
        );
        assert!(out.contains("vaultdata"), "data_dir missing");
        assert!(out.contains("a@b.fr"), "admin email missing");
        assert!(out.contains("test-pass-9f3a"), "admin password missing");
        assert!(out.contains(&secret64()), "cookie_secret not verbatim");
        assert_eq!(
            parsed["server"]["bind_addr"].as_str(),
            Some("127.0.0.1:9090")
        );
        assert_eq!(
            parsed["server"]["base_url"].as_str(),
            Some("http://localhost:9090")
        );
        assert_eq!(parsed["storage"]["data_dir"].as_str(), Some("./vaultdata"));
        assert_eq!(parsed["admin"]["email"].as_str(), Some("a@b.fr"));
        assert_eq!(parsed["admin"]["password"].as_str(), Some("test-pass-9f3a"));
        assert_eq!(
            parsed["session"]["cookie_secret"].as_str(),
            Some(secret64().as_str())
        );
    }

    #[test]
    fn generate_config_escapes_special_characters() {
        let out = generate_config(8080, "./d", "a@b.fr", "p\"ass\\wo#rd", &secret64());
        let parsed: toml::Table = out.parse().expect("special chars must be escaped");
        assert_eq!(parsed["admin"]["password"].as_str(), Some("p\"ass\\wo#rd"));
    }

    #[test]
    fn cookie_secret_is_64_lowercase_hex_and_unique() {
        let s = generate_cookie_secret();
        assert_eq!(s.len(), 64, "must be 64 hex chars (32 bytes)");
        assert!(
            s.chars()
                .all(|c| c.is_ascii_digit() || ('a'..='f').contains(&c)),
            "must be lowercase hex: {s}"
        );
        assert_ne!(s, generate_cookie_secret(), "two calls must differ");
    }

    #[test]
    fn prompt_accepts_defaults_on_empty_lines() {
        let mut reader = BufReader::new("\n\n\n".as_bytes());
        let mut writer = Vec::new();
        let a = prompt_answers(&mut reader, &mut writer).unwrap();
        assert_eq!(a.port, 8080);
        assert_eq!(a.data_dir, "./data");
        assert_eq!(a.admin_email, "admin@example.com");
        assert!(a.admin_password.is_empty(), "password filled by caller");
        let shown = String::from_utf8(writer).unwrap();
        assert!(shown.contains("Port [8080]:"), "got: {shown}");
        assert!(shown.contains("Data dir [./data]:"), "got: {shown}");
        assert!(
            shown.contains("Admin email [admin@example.com]:"),
            "got: {shown}"
        );
    }

    #[test]
    fn prompt_overrides_defaults_and_invalid_port_reprompts() {
        let mut reader = BufReader::new("notaport\n9090\n./vaultdata\na@b.fr\n".as_bytes());
        let mut writer = Vec::new();
        let a = prompt_answers(&mut reader, &mut writer).unwrap();
        assert_eq!(a.port, 9090);
        assert_eq!(a.data_dir, "./vaultdata");
        assert_eq!(a.admin_email, "a@b.fr");
        let shown = String::from_utf8(writer).unwrap();
        assert!(
            shown.contains("Invalid port"),
            "expected re-prompt: {shown}"
        );
    }
}
